#!/usr/bin/env python3
"""Download official CHF exchange rates from the Swiss National Bank (SNB)
data portal and write web/fx-rates.js, so the browser app can fill in the
conversion rates automatically while staying fully offline.

Source: SNB cube "devkum" (Devisenkurse, monthly average and end of month),
https://data.snb.ch/api/cube/devkum/data/csv/en

  yearEnd[YYYY][CCY]  = end-of-month rate of December (rate per 31.12.)
  monthly[CCY][YYYY-MM] = monthly average (used for dividends/interest)
  latest              = most recent end-of-month rates (provisional year end)

Rates are CHF per 1 unit (SNB quotes some currencies per 100 units).
Standard library only. Usage: python3 scripts/update_fx_rates.py [out.js]
"""
import csv
import io
import json
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://data.snb.ch/api/cube/devkum/data/csv/en"
FIRST_YEAR = 2018
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "web" / "fx-rates.js"


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as r:
        text = r.read().decode("utf-8-sig")
    published = (re.search(r'"PublishingDate";"([^"]+)"', text) or [None, ""])[1]
    body = text[text.index('"Date";'):]
    year_end, monthly, month_end = {}, {}, {}
    for row in csv.DictReader(io.StringIO(body), delimiter=";"):
        m = re.fullmatch(r"([A-Z]{3})(1|100)", row["D1"] or "")
        if not m or not row["Value"]:
            continue
        ym = row["Date"]
        if int(ym[:4]) < FIRST_YEAR:
            continue
        ccy, unit = m[1], int(m[2])
        v = round(float(row["Value"]) / unit, 6)
        if row["D0"] == "M0":
            monthly.setdefault(ccy, {})[ym] = v
        elif row["D0"] == "M1":
            month_end.setdefault(ym, {})[ccy] = v
            if ym.endswith("-12"):
                year_end.setdefault(ym[:4], {})[ccy] = v
    last = max(month_end)
    data = {
        "source": "Schweizerische Nationalbank (SNB), Devisenkurse devkum",
        "published": published,
        "yearEnd": year_end,
        "latest": {"month": last, "rates": month_end[last]},
        "monthly": monthly,
    }
    js = ("/* Generated by scripts/update_fx_rates.py from the SNB data portal - do not edit. */\n"
          "(function (root) { root.SQFX = " + json.dumps(data, separators=(",", ":"), sort_keys=True) + "; })"
          "(typeof self !== \"undefined\" ? self : this);\n"
          "if (typeof module === \"object\" && module.exports) module.exports = (typeof self !== \"undefined\" ? self : this).SQFX;\n")
    OUT.write_text(js, encoding="utf-8")
    print(f"wrote {OUT} ({len(js) // 1024} KB), year ends {sorted(year_end)}, latest {last}, published {published}")


if __name__ == "__main__":
    main()
